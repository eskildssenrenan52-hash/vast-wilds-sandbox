export const DETAILED_PET_MAP: Record<string, DetailedPetDef> = Object.fromEntries(
  DETAILED_PETS.map((p) => [p.id, p])
);

export function getPetDefOrFallback(id: SpiritId): DetailedPetDef | null {
  if (id === 'none') return null;
  return DETAILED_PET_MAP[id] ?? DETAILED_PETS[0];
}

export function computePetLevelBonuses(petId: SpiritId, rawLevel: number) {
  const def = getPetDefOrFallback(petId);
  if (!def) {
    return { level: 1, collectRange: 0, shootInterval: 999, xpBonus: 1, attackBonus: 0 };
  }
  const lv = Math.max(1, Math.min(10, Math.floor(rawLevel)));
  return {
    level: lv,
    collectRange: Math.round(def.collectRange + (lv - 1) * 5),
    shootInterval: Math.max(1.3, Number((def.shootInterval * Math.pow(0.94, lv - 1)).toFixed(2))),
    xpBonus: Number((def.xpBonus + (lv - 1) * 0.03).toFixed(2)),
    attackBonus: def.attackBonus + Math.floor((lv - 1) / 3),
  };
}

export function getPetNextLevelXp(level: number): number {
  return 40 + (level - 1) * 25;
}

/**
 * Shared high-detail animated Pet renderer used by both PetsModal, Title Screen, and in-game PixelRenderer.
 * Draws layered glow, bond-tier rotating arcane rings, wing/tail afterimage trail, orbital shards, and 2x sub-pixel sprite.
 */
export function drawDetailedPetShowcase(
  ctx: CanvasRenderingContext2D,
  pet: DetailedPetDef,
  time: number,
  cx: number,
  cy: number,
  opts: {
    facing?: 1 | -1;
    bondLv?: number;
    drawBackdrop?: boolean;
    scale?: number;
  } = {}
): void {
  const bondLv = Math.max(1, Math.min(10, opts.bondLv ?? 1));
  const facing = opts.facing ?? 1;
  const sc = opts.scale ?? 1;
  const bob = Math.sin(time * 5.2) * 1.4;
  const px = cx;
  const py = cy + bob;

  ctx.save();
  ctx.translate(px, py);
  ctx.scale(sc, sc);

  // Radial elemental aura
  const auraR = 11 + Math.min(5, bondLv * 0.5);
  const grad = ctx.createRadialGradient(0, 0, 1, 0, 0, auraR);
  grad.addColorStop(0, pet.color + (opts.drawBackdrop ? '75' : '50'));
  grad.addColorStop(0.6, pet.secondaryColor + '25');
  grad.addColorStop(1, '#08051000');
  ctx.fillStyle = grad;
  ctx.fillRect(-auraR, -auraR, auraR * 2, auraR * 2);

  // Bond Lv >= 3 rotating sigil ring; Lv >= 7 dual sacred ring
  if (bondLv >= 3 || pet.animStyle === 'seraph_halo' || pet.animStyle === 'orbit_shards') {
    const ringR = 10.5 + Math.sin(time * 3) * 0.5;
    ctx.globalAlpha = 0.42 + bondLv * 0.03;
    ctx.strokeStyle = pet.secondaryColor;
    ctx.lineWidth = 0.7;
    ctx.beginPath();
    ctx.arc(0, 0, ringR, 0, Math.PI * 2);
    ctx.stroke();

    const ticks = bondLv >= 7 ? 6 : 4;
    for (let i = 0; i < ticks; i++) {
      const a = time * 2.1 + (Math.PI * 2 * i) / ticks;
      const sx = Math.cos(a) * ringR;
      const sy = Math.sin(a) * ringR;
      ctx.fillStyle = i % 2 === 0 ? '#ffffff' : pet.color;
      ctx.fillRect(Math.round(sx * 2) * 0.5 - 0.5, Math.round(sy * 2) * 0.5 - 0.5, 1, 1);
    }
    ctx.globalAlpha = 1;
  }

  // Seraph golden halo or elemental crest
  if (pet.animStyle === 'seraph_halo') {
    const hy = -9 + Math.sin(time * 4.5) * 0.6;
    ctx.strokeStyle = '#ffe066';
    ctx.lineWidth = 0.85;
    ctx.beginPath();
    ctx.ellipse(0, hy, 5.5, 1.4, 0, 0, Math.PI * 2);
    ctx.stroke();
    ctx.fillStyle = '#ffffff';
    ctx.fillRect(-1.5, hy - 1.5, 3, 0.7);
  }

  // Soft trailing ghost afterimage for fluid flight feel
  const frameIdx = Math.floor(time * 6.5) % pet.frames.length;
  const prevIdx = (frameIdx + pet.frames.length - 1) % pet.frames.length;
  const trailShift = -facing * 1.8;

  ctx.save();
  ctx.globalAlpha = 0.24;
  drawPixelSprite(
    ctx,
    `pet18_${pet.id}_f${prevIdx}`,
    pet.frames[prevIdx],
    pet.palette,
    -9 + trailShift,
    -7.4,
    facing < 0,
    1,
    1,
    false
  );
  ctx.restore();

  // Offset so 18x16 sprite centers cleanly on (0, 0)
  drawPixelSprite(
    ctx,
    `pet18_${pet.id}_f${frameIdx}`,
    pet.frames[frameIdx],
    pet.palette,
    -9,
    -8,
    facing < 0,
    1,
    1,
    false
  );

  // Foreground orbital shards / embers / petals
  const orbCount = pet.animStyle === 'orbit_shards' ? 3 : bondLv >= 5 ? 2 : 1;
  for (let i = 0; i < orbCount; i++) {
    const a = time * 3.4 + (Math.PI * 2 * i) / orbCount;
    const ox = Math.cos(a) * 10.5;
    const oy = Math.sin(a) * 5.2;
    if (Math.sin(a) >= -0.2) {
      ctx.fillStyle = '#090712';
      ctx.fillRect(Math.round(ox * 2) * 0.5 - 1, Math.round(oy * 2) * 0.5 - 1, 2, 2);
      ctx.fillStyle = i % 2 === 0 ? pet.secondaryColor : '#ffffff';
      ctx.fillRect(Math.round(ox * 2) * 0.5 - 0.5, Math.round(oy * 2) * 0.5 - 0.5, 1, 1);
    }
  }

  // Rising elemental sparks
  for (let i = 0; i < 3; i++) {
    const p = (time * 0.8 + i * 0.33) % 1;
    const ex = Math.sin(time * 3 + i * 2.1) * 7.5;
    const ey = 6 - p * 15;
    ctx.globalAlpha = Math.sin(p * Math.PI) * 0.85;
    ctx.fillStyle = i % 2 === 0 ? pet.color : '#ffffff';
    ctx.fillRect(Math.round(ex * 2) * 0.5, Math.round(ey * 2) * 0.5, 0.8, 0.8);
  }

  ctx.restore();
}
