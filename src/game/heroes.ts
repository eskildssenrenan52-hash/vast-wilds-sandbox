export function getHeroElement(heroId: HeroId | string | undefined): ElementType {
  const h = getHeroDef(heroId);
  return h.element ?? DEFAULT_HERO_ELEMENT[h.id] ?? 'astral';
}

export function getHeroDef(id: HeroId | string | undefined): HeroDef {
  if (id && id in HERO_MAP) {
    return HERO_MAP[id as HeroId];
  }
  return HERO_MAP.lyra;
}

export function getHeroSkinDef(heroId: HeroId | string | undefined, skinId?: string): HeroSkinDef {
  const hero = getHeroDef(heroId);
  if (skinId) {
    const found = hero.skins.find((s) => s.id === skinId);
    if (found) return found;
  }
  return hero.skins[0];
}

export const STARTER_HERO_IDS: HeroId[] = ['lyra', 'zephyr', 'nyx', 'ignis'];

export interface HeroUnlockReq {
  freeStarter: boolean;
  coinCost: number;
  requiredLevel: number;
}

export function getHeroUnlockReq(hero: HeroDef): HeroUnlockReq {
  if (STARTER_HERO_IDS.includes(hero.id)) {
    return { freeStarter: true, coinCost: 0, requiredLevel: 1 };
  }
  const sameRarity = HEROES.filter((h) => h.rarity === hero.rarity && !STARTER_HERO_IDS.includes(h.id));
  const tierIdx = Math.max(0, sameRarity.findIndex((h) => h.id === hero.id));
  switch (hero.rarity) {
    case 'Comum':
      return {
        freeStarter: false,
        coinCost: 15 + tierIdx * 5,
        requiredLevel: 1 + (tierIdx % 2),
      };
    case 'Raro':
      return {
        freeStarter: false,
        coinCost: 35 + tierIdx * 8,
        requiredLevel: 2 + Math.floor(tierIdx / 2),
      };
    case 'Super-Raro':
      return {
        freeStarter: false,
        coinCost: 70 + tierIdx * 10,
        requiredLevel: 5 + Math.floor(tierIdx / 2),
      };
    case 'Épico':
      return {
        freeStarter: false,
        coinCost: 115 + tierIdx * 12,
        requiredLevel: 8 + Math.floor(tierIdx / 2),
      };
    case 'Mítico':
      return {
        freeStarter: false,
        coinCost: 175 + tierIdx * 15,
        requiredLevel: 11 + Math.floor(tierIdx / 2),
      };
    case 'Lendário':
      return {
        freeStarter: false,
        coinCost: 250 + tierIdx * 20,
        requiredLevel: 15 + tierIdx,
      };
    default:
      return { freeStarter: false, coinCost: 25, requiredLevel: 2 };
  }
}

export function canUnlockHero(
  hero: HeroDef,
  astralCoins: number,
  playerLevel: number
): {
  canUnlock: boolean;
  missingLevel: number;
  missingCoins: number;
  req: HeroUnlockReq;
} {
  const req = getHeroUnlockReq(hero);
  const missingLevel = Math.max(0, req.requiredLevel - playerLevel);
  const missingCoins = Math.max(0, req.coinCost - astralCoins);
  return {
    canUnlock: missingLevel === 0 && missingCoins === 0,
    missingLevel,
    missingCoins,
    req,
  };
}

