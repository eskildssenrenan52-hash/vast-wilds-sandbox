// Helper for bespoke 9-row tall non-squashed heads + 6-row sculpted 10px torsos on the remaining 24 champions
function makeDetailedChampion(
  headRows: [string, string, string, string, string, string, string, string, string], // 9 tall rows!
  eyeRowIdx: number, // index of upper eye row (4 or 5)
  torsoCollar: string,
  torsoChest: string,
  torsoWaist: string,
  wingsIdle?: string[],
  wingsFlap?: string[],
  eyeBlinkChars = 's'
): HeroSpriteFrames {
  const upperIdx = eyeRowIdx;
  const lowerIdx = Math.min(7, eyeRowIdx + 1);

  const headNormal = [...headRows];
  const headBlink = [...headRows];
  headBlink[upperIdx] = headRows[upperIdx].replace(/[we]/g, eyeBlinkChars);
  headBlink[lowerIdx] = headRows[lowerIdx].replace(/[we]/g, eyeBlinkChars === 's' ? 'S' : eyeBlinkChars);

  const headUp = [...headRows];
  if (upperIdx >= 2) {
    headUp[upperIdx - 1] = headRows[upperIdx];
    headUp[upperIdx] = headRows[lowerIdx];
    headUp[lowerIdx] = headRows[Math.min(8, lowerIdx + 1)];
  }

  return buildCustomHeroFrames(
    headNormal,
    headBlink,
    headUp,
    TORSO_TUNIC_IDLE(torsoCollar, torsoChest, torsoWaist),
    TORSO_TUNIC_ACTION(torsoCollar, torsoChest),
    TORSO_TUNIC_DASH(torsoCollar),
    [[]],
    wingsIdle,
    wingsFlap
  );
}

