const spriteCache = new Map<string, HTMLCanvasElement>();

function isOutlineChar(ch: string): boolean {
  return ch === 'o';
}

function isHighlightChar(ch: string): boolean {
  return ch === 'g' || ch === 'G' || ch === 'H' || ch === 'A' || ch === 'e' || ch === 'w' || ch === 'c';
}

function getOrBakeSprite(
  key: string,
  rows: string[],
  palette: PixelPalette
): HTMLCanvasElement | null {
  if (typeof document === 'undefined' || !rows || rows.length === 0) return null;
  const cached = spriteCache.get(key);
  if (cached) return cached;

  const h = rows.length;
  const w = rows[0]?.length ?? 1;
  const scale = 2;
  const c = document.createElement('canvas');
  c.width = w * scale;
  c.height = h * scale;
  const g = c.getContext('2d');
  if (!g) return null;

  const at = (x: number, y: number): string => {
    if (y < 0 || y >= h) return '.';
    const row = rows[y];
    if (!row || x < 0 || x >= row.length) return '.';
    const ch = row[x];
    return ch === ' ' ? '.' : ch;
  };
  const isSolid = (x: number, y: number): boolean => {
    const ch = at(x, y);
    return ch !== '.' && Boolean(palette[ch]);
  };

  for (let y = 0; y < h; y++) {
    const row = rows[y];
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.' || ch === ' ') continue;
      const col = palette[ch];
      if (!col) continue;

      const sx = x * 2;
      const sy = y * 2;
      const up = isSolid(x, y - 1);
      const dn = isSolid(x, y + 1);
      const lf = isSolid(x - 1, y);
      const rt = isSolid(x + 1, y);

      if (isOutlineChar(ch)) {
        // Draw 2x2 outline block with crisp sub-pixel corner chamfers on convex outer corners
        g.fillStyle = col;
        g.fillRect(sx, sy, 2, 2);
        if (!up && !lf && (dn || rt)) {
          g.clearRect(sx, sy, 1, 1);
        }
        if (!up && !rt && (dn || lf)) {
          g.clearRect(sx + 1, sy, 1, 1);
        }
        if (!dn && !lf && (up || rt)) {
          g.clearRect(sx, sy + 1, 1, 1);
        }
        if (!dn && !rt && (up || lf)) {
          g.clearRect(sx + 1, sy + 1, 1, 1);
        }
      } else {
        g.fillStyle = col;
        g.fillRect(sx, sy, 2, 2);

        // Directional top-left rim light & bottom-right core shadow on 2x sub-pixels
        const upCh = at(x, y - 1);
        const lfCh = at(x - 1, y);
        const dnCh = at(x, y + 1);
        const rtCh = at(x + 1, y);
        const topLeftExposed = !up || isOutlineChar(upCh) || !lf || isOutlineChar(lfCh);
        const botRightExposed = !dn || isOutlineChar(dnCh) || !rt || isOutlineChar(rtCh);

        if (topLeftExposed && (dn || rt)) {
          g.fillStyle = isHighlightChar(ch) ? 'rgba(255,255,255,0.28)' : 'rgba(255,255,255,0.14)';
          g.fillRect(sx, sy, 1, 1);
          if (!up || isOutlineChar(upCh)) {
            g.fillRect(sx + 1, sy, 1, 1);
          }
        }
        if (botRightExposed && (up || lf)) {
          g.fillStyle = 'rgba(4,2,12,0.22)';
          g.fillRect(sx + 1, sy + 1, 1, 1);
        }
      }
    }
  }
  spriteCache.set(key, c);
  return c;
}

export function drawPixelSprite(
  ctx: CanvasRenderingContext2D,
  key: string,
  rows: string[],
  palette: PixelPalette,
  dx: number,
  dy: number,
  flipX = false,
  scaleX = 1,
  scaleY = 1,
  anchorBottomCenter = false
): void {
  const img = getOrBakeSprite(key, rows, palette);
  if (!img) return;

  const logicalW = img.width * 0.5;
  const logicalH = img.height * 0.5;
  ctx.save();
  if (anchorBottomCenter) {
    ctx.translate(Math.round(dx * 2) * 0.5, Math.round(dy * 2) * 0.5);
    ctx.scale((flipX ? -1 : 1) * scaleX, scaleY);
    ctx.drawImage(img, Math.round(-logicalW) * 0.5, -logicalH, logicalW, logicalH);
  } else {
    ctx.translate(Math.round((dx + logicalW * 0.5) * 2) * 0.5, Math.round((dy + logicalH * 0.5) * 2) * 0.5);
    ctx.scale((flipX ? -1 : 1) * scaleX, scaleY);
    ctx.drawImage(img, Math.round(-logicalW) * 0.5, Math.round(-logicalH) * 0.5, logicalW, logicalH);
  }
  ctx.restore();
}

export function drawTintedSprite(
  ctx: CanvasRenderingContext2D,
  key: string,
  rows: string[],
  tintColor: string,
  dx: number,
  dy: number,
  flipX = false,
  anchorBottomCenter = true
): void {
  if (!rows || rows.length === 0) return;
  const palette: PixelPalette = {
    o: tintColor,
    h: tintColor,
    H: '#ffffff',
    d: tintColor,
    s: tintColor,
    S: tintColor,
    e: '#ffffff',
    w: '#ffffff',
    D: tintColor,
    C: tintColor,
    c: '#ffffff',
    g: '#ffffff',
    G: '#ffffff',
    b: tintColor,
    L: tintColor,
    a: tintColor,
    A: '#ffffff',
  };
  drawPixelSprite(ctx, `tint_${key}_${tintColor}`, rows, palette, dx, dy, flipX, 1, 1, anchorBottomCenter);
}

