function makeBoss24x18(c1: string, c2: string, core: string, style: 0 | 1 | 2 | 3): SpriteEntry {
  const palette = { o: '#070410', a: c1, b: c2, c: core, w: '#ffffff', d: '#1e1b2e' };
  const f0 =
    style === 0
      ? [
          '...oo....oooooo....oo...',
          '..obbo..obwwwwbo..obbo..',
          '..obbaooaaaaaaaaaoabbo..',
          '...oooaaaawwwwaaaaooo...',
          '..oaaaawccccccccwaaaao..',
          '.oaawwcccbbbbbbcccwwaao.',
          '..oaaaacccwwwwcccaaaao..',
          '...oaaabbbbbbbbbbaaao...',
          '..obbbbaaawwwwaaaabbbbo.',
          '.obb..ooaaaaaaaaaoo..bbo',
          '.oo....oadd..ddao....oo.',
          '.......oad....dao.......',
          '.......oo......oo.......',
        ]
      : style === 1
        ? [
            '.....oooo......oooo.....',
            '....oaccbo....obccao....',
            '...oaaaaaoooooaaaaaao...',
            '..oaaabbbbbbbbbbbbaaao..',
            '.oaabboooowwwwoooobbaao.',
            '.oaabbooccwwwwccoobbaao.',
            '..oaabbbbccccccbbbbaao..',
            '...ooaaaabwwwwbaaaaoo...',
            '..obbbbaaaaaaaaaabbbbo..',
            '.obb.oaaadddddaaao.bbo..',
            '.oo...oaa..oo..aao..oo..',
            '......oa...oo...ao......',
            '......o..........o......',
          ]
        : style === 2
          ? [
              '..oooo....oooo....oooo..',
              '.obccbo..owwwwo..obccbo.',
              '.obwwbo..obwwbo..obwwbo.',
              '..oaaaoooaaaaaoooaaaao..',
              '..oaaaaaaaaaaaaaaaaaao..',
              '..oaacccccaaaabbbbbaao..',
              '...oaaaaaaccccaaaaao....'.padEnd(24, '.'),
              '...ooaaaccccccccaaaoo...',
              '....oaaaaaaaaaaaaaao....',
              '...oaaaaa.oaao.aaaaao...',
              '..oaaaoo..oaao..ooaaao..',
              '..ooo.....oooo.....ooo..',
              '........................',
            ]
          : [
              '...oo...oooooooo...oo...',
              '..occo.ocwwwwwwco.occo..',
              '..occboobbbbbbbboobcco..',
              '...oooaaaaaaaaaaaaooo...',
              '..oaaawwwwwwwwwwwwaaaao.',
              '.oaawwccwwwwwwwwccwwaao.',
              '..ooaaaaaccccccaaaaaoo..',
              '...oaaabbbwwwwbbbaaao...',
              '..obbbbaabbbbbbaabbbbo..',
              '.obb..oobbbbbbbboo..bbo.',
              '.oo....oad....dao....oo.',
              '.......oad....dao.......',
              '.......oo......oo.......',
            ];
  const pad = [...f0, '........................', '........................', '........................', '........................', '........................'].slice(0, 18);
  const f1 = pad.map((row) => row.replace(/c/g, 'x').replace(/b/g, 'c').replace(/x/g, 'b'));
  const f2 = pad.map((row) => row.replace(/w/g, 'c').replace(/b/g, 'w').slice(0, 24));
  return { palette, frames: [pad, f1, f2] };
}

